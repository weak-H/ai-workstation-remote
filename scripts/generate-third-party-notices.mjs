import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(await fs.readFile(path.join(root, "package-lock.json"), "utf8"));
const outputDirectory = path.join(root, "licenses");
const noticePattern = /^(?:licen[cs]e|copying|notice|copyright|thirdpartynoticetext)(?:[._-].*)?$/i;

const dependencies = [];
const missingLicense = [];
const missingNotice = [];

for (const [lockPath, metadata] of Object.entries(lock.packages ?? {})) {
  if (!lockPath.includes("node_modules/") || metadata.link) continue;

  const packageDirectory = path.join(root, lockPath);
  const installed = await fs
    .access(path.join(packageDirectory, "package.json"))
    .then(() => true)
    .catch(() => false);
  const packageJson = installed
    ? JSON.parse(await fs.readFile(path.join(packageDirectory, "package.json"), "utf8"))
    : {};
  const name = packageJson.name ?? lockPath.slice(lockPath.lastIndexOf("node_modules/") + 13);
  const version = metadata.version ?? packageJson.version;
  const legacyLicenses = Array.isArray(packageJson.licenses)
    ? packageJson.licenses.map((entry) => entry.type).filter(Boolean).join(" OR ")
    : undefined;
  const license = metadata.license ?? packageJson.license ?? legacyLicenses;
  if (!license) missingLicense.push(`${name}@${version}`);

  const filenames = installed
    ? (await fs.readdir(packageDirectory))
        .filter((filename) => noticePattern.test(filename))
        .sort((left, right) => left.localeCompare(right))
    : [];
  if (installed && !metadata.optional && filenames.length === 0) {
    missingNotice.push(`${name}@${version}`);
  }

  dependencies.push({
    name,
    version,
    license: license ?? "UNKNOWN",
    scope: metadata.dev ? "development" : metadata.optional ? "optional" : "runtime",
    installed,
    lockPath,
    packageDirectory,
    filenames,
  });
}

dependencies.sort((left, right) =>
  `${left.name}@${left.version}:${left.lockPath}`.localeCompare(
    `${right.name}@${right.version}:${right.lockPath}`,
  ),
);

if (missingLicense.length || missingNotice.length) {
  const details = [];
  if (missingLicense.length) details.push(`Missing license metadata: ${missingLicense.join(", ")}`);
  if (missingNotice.length) details.push(`Missing license/notice files: ${missingNotice.join(", ")}`);
  throw new Error(details.join("\n"));
}

const inventory = [
  "# Locked npm dependency inventory",
  "",
  "> Generated by `npm run licenses`. Do not edit manually.",
  "",
  `Lockfile version: ${lock.lockfileVersion}`,
  "",
  "| Package | Version | Declared license | Scope |",
  "| --- | --- | --- | --- |",
  ...dependencies.map(
    ({ name, version, license, scope }) =>
      `| \`${name.replaceAll("|", "\\|")}\` | \`${version}\` | ${String(license).replaceAll("|", "\\|")} | ${scope} |`,
  ),
  "",
].join("\n");

const notices = [
  "AI Workstation Remote - npm dependency license notices",
  "Generated by `npm run licenses`. Do not edit manually.",
  "",
];

for (const dependency of dependencies) {
  if (!dependency.installed) continue;
  for (const filename of dependency.filenames) {
    const heading = `${dependency.name}@${dependency.version} - ${filename}`;
    notices.push("=".repeat(heading.length), heading, "=".repeat(heading.length), "");
    notices.push(await fs.readFile(path.join(dependency.packageDirectory, filename), "utf8"));
    notices.push("");
  }
}

await fs.mkdir(outputDirectory, { recursive: true });
await fs.writeFile(path.join(outputDirectory, "npm-dependencies.md"), inventory, "utf8");
await fs.writeFile(path.join(outputDirectory, "npm-notices.txt"), notices.join("\n"), "utf8");

console.log(`Recorded ${dependencies.length} locked npm packages.`);
