export type MessageKey = keyof typeof baseMessages["zh-CN"];
type MessageParams = Record<string, string | number>;

export const localeOptions = Object.entries(localeNames).map(([value, label]) => ({ value: value as Locale, label }));

const languageStorageKey = "ai-workstation-language";

export function initialLocale(storage: Pick<Storage, "getItem"> | undefined, _browserLanguage: string): Locale {
  const stored = storage?.getItem(languageStorageKey);
  if (stored && stored in localeNames) return stored as Locale;
  return "en";
}

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const localized = locale === "en" || locale === "zh-CN"
    ? baseMessages[locale][key]
    : (additionalMessages[locale] as Partial<Record<MessageKey, string>>)[key];
  const template = localized ?? baseMessages.en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}

export function localeDirection(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" || locale === "fa" ? "rtl" : "ltr";
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: MessageParams) => string;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => initialLocale(window.localStorage, window.navigator.language));

  useEffect(() => {
    window.localStorage.setItem(languageStorageKey, locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = localeDirection(locale);
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, params) => translate(locale, key, params),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
